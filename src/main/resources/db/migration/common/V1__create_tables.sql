CREATE TABLE laboratories (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(20)  NOT NULL,
    name      VARCHAR(100) NOT NULL,
    building  VARCHAR(60)  NOT NULL,
    capacity  INTEGER      NOT NULL,
    opens_at  TIME         NOT NULL,
    closes_at TIME         NOT NULL,
    active    BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_laboratories_code UNIQUE (code),
    CONSTRAINT ck_laboratories_capacity CHECK (capacity > 0),
    CONSTRAINT ck_laboratories_hours CHECK (closes_at > opens_at)
);

CREATE TABLE reservations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratory_id   BIGINT       NOT NULL,
    requester_name  VARCHAR(100) NOT NULL,
    requester_email VARCHAR(120) NOT NULL,
    purpose         VARCHAR(200) NOT NULL,
    attendees       INTEGER      NOT NULL,
    starts_at       TIMESTAMP    NOT NULL,
    ends_at         TIMESTAMP    NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    cancelled_at    TIMESTAMP,
    CONSTRAINT fk_reservations_laboratory FOREIGN KEY (laboratory_id) REFERENCES laboratories (id),
    CONSTRAINT ck_reservations_attendees CHECK (attendees > 0),
    CONSTRAINT ck_reservations_period CHECK (ends_at > starts_at),
    CONSTRAINT ck_reservations_status CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);

CREATE INDEX idx_reservations_lab_period ON reservations (laboratory_id, starts_at);
CREATE INDEX idx_reservations_email ON reservations (requester_email);
